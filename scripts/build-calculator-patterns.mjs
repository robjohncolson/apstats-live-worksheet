#!/usr/bin/env node
// Builds apstat-park/calculator-patterns.mjs (and the relay's byte-identical copy) from
// ti84-pattern-recognition-data.json (APSTAT_PARK_TRAINER_ABSORB_SPEC §4). The JSON stays the
// source: edit it, run this, commit both outputs.
//
//   node scripts/build-calculator-patterns.mjs           write both copies
//   node scripts/build-calculator-patterns.mjs --check   exit 1 if either copy is stale (no writes)
//
// What is kept: the four discriminating signature fields (dataType, parameterType, questionType,
// sampleStructure) plus distributionFamily and unit; every confusion pair; every canonical
// problem's stem and unit. Keywords, framework skills and the precomputed distractor sets are not
// needed by the park (calculator-recognition.mjs ranks distractors from the pairs and units).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(ROOT, 'ti84-pattern-recognition-data.json');
export const OUTPUTS = [
  path.join(ROOT, 'apstat-park', 'calculator-patterns.mjs'),
  path.join(ROOT, '..', 'curriculum_render', 'railway-server', 'apstat-park', 'calculator-patterns.mjs'),
];
const SIGNATURE_FIELDS = ['dataType', 'parameterType', 'questionType', 'sampleStructure', 'distributionFamily', 'unit'];

const sortedKeys = object => Object.keys(object).sort();
const literal = value => JSON.stringify(value);

export function buildPatternsModule(data) {
  const lines = [];
  lines.push('// GENERATED by scripts/build-calculator-patterns.mjs from ti84-pattern-recognition-data.json');
  lines.push('// (meta.version ' + data.meta.version + ', generated ' + data.meta.generated + '). Do not edit: edit the JSON and rebuild.');
  lines.push('// Shared byte-identical between the park client and the relay (APSTAT_PARK_TRAINER_ABSORB_SPEC §4).');
  lines.push('');
  lines.push('// skillId -> the signals that tell procedures apart (calculator-recognition.mjs reads these in order).');
  lines.push('export const PATTERN_SIGNATURES = {');
  for (const id of sortedKeys(data.patternSignatures)) {
    const signature = data.patternSignatures[id];
    const fields = SIGNATURE_FIELDS.map(field => literal(field) + ': ' + literal(signature[field] ?? null)).join(', ');
    lines.push('  ' + literal(id) + ': { ' + fields + ' },');
  }
  lines.push('};');
  lines.push('');
  lines.push('// Pairs students confuse, with the contrast a wrong pick is told (first sentence used).');
  lines.push('export const CONFUSION_PAIRS = [');
  for (const pair of data.confusionMatrix) {
    lines.push('  { a: ' + literal(pair.a) + ', b: ' + literal(pair.b) + ', type: ' + literal(pair.type) + ', contrast: ' + literal(pair.contrast) + ' },');
  }
  lines.push('];');
  lines.push('');
  lines.push('// skillId -> word problems that call for exactly that procedure.');
  lines.push('export const CANONICAL_PROBLEMS = {');
  for (const id of sortedKeys(data.canonicalProblems)) {
    lines.push('  ' + literal(id) + ': [');
    for (const problem of data.canonicalProblems[id]) {
      lines.push('    { stem: ' + literal(problem.stem) + ', unit: ' + literal(problem.unit ?? null) + ' },');
    }
    lines.push('  ],');
  }
  lines.push('};');
  lines.push('');
  return lines.join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const data = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const output = buildPatternsModule(data);
  let stale = 0;
  for (const file of OUTPUTS) {
    const parentMissing = !existsSync(path.dirname(file));
    if (parentMissing) { console.log('skip (no such directory): ' + file); continue; }
    const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
    if (current === output) { console.log('up to date: ' + path.relative(ROOT, file)); continue; }
    if (check) { console.log('STALE: ' + path.relative(ROOT, file)); stale++; continue; }
    writeFileSync(file, output);
    console.log('wrote ' + path.relative(ROOT, file));
  }
  if (stale) process.exit(1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
