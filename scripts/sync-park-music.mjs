// Copies the tracker handoff (handoff/audio/tracker/, Grok's editing home: demo.html + tools/smps_export.py, keen_export.py)
// into the park's runtime tree, apstat-park/music/. The three classic scripts are wrapped as ES
// modules so the park imports them with its ?v=<APP_BUILD> query like every other park module;
// the song JSON files are copied byte for byte (their `mix` blocks are the teacher's approved
// settings). apstat-park/music-sync.test.mjs fails when the copies drift from the handoff.
//   node scripts/sync-park-music.mjs          # write
//   node scripts/sync-park-music.mjs --check  # exit 1 when anything differs
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const HANDOFF = resolve(root, 'handoff/audio/tracker');
export const RUNTIME = resolve(root, 'apstat-park/music');
export const SCRIPTS = ['tracker-engine.js', 'vibe.js', 'palette.js'];
// Original Sega data (TRACKER_SPEC §7c): the S3K sound-effect set and the DAC drum kits the
// Genesis songs reference (song.drumKit, song.sfxMap). Copied byte for byte, like the songs.
export const DATA = ['sfx/genesis-s3k.json', 'samples/s3.json', 'samples/sk.json'];
// Frozen songs (TRACKER_SPEC §7e): each song pre-rendered by the real engine into frozen/<id>.ogg
// ([intro][loop], Vorbis) with a frozen/<id>.json sidecar (loop points, songSha1, engineSha1,
// renderMaster). The park loops the audio instead of scheduling rows, so a main-thread stall can
// no longer drop notes. Only the full mix is shipped: low power exists to save CPU, and a buffer
// source costs none (the SFX voices still honour it). Copied byte for byte.
export const FROZEN_DIR = 'frozen';

export function wrapClassic(name, source) {
  return '// Generated by scripts/sync-park-music.mjs from handoff/audio/tracker/' + name + ' — edit the handoff, then re-run the sync.\n'
    + 'const module = { exports: {} };\n'
    + source.replace(/\r\n/g, '\n')
    + (source.endsWith('\n') ? '' : '\n')
    + 'export default module.exports;\n';
}

export function songFiles() {
  return readdirSync(resolve(HANDOFF, 'songs')).filter(f => f.endsWith('.json')).sort();
}
export function songIds() { return songFiles().map(f => f.replace(/\.json$/, '')); }

// Published paths of a song's freeze (sidecar first).
export function frozenFiles(id) { return [FROZEN_DIR + '/' + id + '.json', FROZEN_DIR + '/' + id + '.ogg']; }

// [published path, expected bytes] for the frozen songs. A song without a freeze in the handoff
// is simply not frozen (the park falls back to live scheduling for it).
export function expectedBinary() {
  const out = [];
  for (const id of songIds()) {
    const files = frozenFiles(id);
    if (!files.every(p => existsSync(resolve(HANDOFF, p)))) continue;
    for (const p of files) out.push([p, readFileSync(resolve(HANDOFF, p))]);
  }
  return out;
}

const sha1 = buf => createHash('sha1').update(buf).digest('hex');
// A freeze is stale when the song or the engine's synthesis changed after it was rendered: the
// sidecar pins both (TRACKER_SPEC §7e: re-run tools/offline/freeze.js <id>). Returns the reasons.
export function staleFreezes() {
  const out = [], engineSha = sha1(readFileSync(resolve(HANDOFF, 'tracker-engine.js')));
  for (const id of songIds()) {
    const side = resolve(HANDOFF, frozenFiles(id)[0]);
    if (!existsSync(side)) continue;
    const meta = JSON.parse(readFileSync(side, 'utf8'));
    if (meta.songSha1 !== sha1(readFileSync(resolve(HANDOFF, 'songs', id + '.json')))) out.push(id + ': songs/' + id + '.json changed since the freeze');
    if (meta.engineSha1 !== engineSha) out.push(id + ': tracker-engine.js changed since the freeze');
  }
  return out;
}

// [published path, expected contents] for everything the sync owns.
export function expected() {
  const out = [];
  for (const name of SCRIPTS) {
    out.push([name.replace(/\.js$/, '.mjs'), wrapClassic(name, readFileSync(resolve(HANDOFF, name), 'utf8'))]);
  }
  for (const file of songFiles()) out.push(['songs/' + file, readFileSync(resolve(HANDOFF, 'songs', file), 'utf8')]);
  for (const path of DATA) out.push([path, readFileSync(resolve(HANDOFF, path), 'utf8')]);
  return out;
}

// Stale songs: a song removed from the handoff must disappear from the runtime tree too.
export function staleSongs() {
  const dir = resolve(RUNTIME, 'songs');
  if (!existsSync(dir)) return [];
  const live = new Set(songFiles());
  return readdirSync(dir).filter(f => f.endsWith('.json') && !live.has(f)).map(f => 'songs/' + f);
}

// Frozen files for songs that left the handoff, or freezes the handoff no longer has.
export function staleFrozen() {
  const dir = resolve(RUNTIME, FROZEN_DIR);
  if (!existsSync(dir)) return [];
  const live = new Set(expectedBinary().map(([p]) => p));
  return readdirSync(dir).map(f => FROZEN_DIR + '/' + f).filter(p => !live.has(p));
}

export function drift() {
  const out = [];
  for (const [path, body] of expected()) {
    const target = resolve(RUNTIME, path);
    if (!existsSync(target) || readFileSync(target, 'utf8') !== body) out.push(path);
  }
  for (const [path, bytes] of expectedBinary()) {
    const target = resolve(RUNTIME, path);
    if (!existsSync(target) || !readFileSync(target).equals(bytes)) out.push(path);
  }
  return out.concat(staleSongs(), staleFrozen());
}

function main() {
  const check = process.argv.includes('--check');
  if (check) {
    const stale = drift();
    if (stale.length) { console.error('park music out of sync: ' + stale.join(', ')); process.exit(1); }
    console.log('park music in sync');
    return;
  }
  const stale = staleFreezes();
  if (stale.length) { console.error('stale freeze in the handoff (re-run tools/offline/freeze.js): ' + stale.join('; ')); process.exit(1); }
  for (const sub of ['songs', 'sfx', 'samples', FROZEN_DIR]) mkdirSync(resolve(RUNTIME, sub), { recursive: true });
  for (const [path, body] of expected().concat(expectedBinary())) {
    writeFileSync(resolve(RUNTIME, path), body);
    console.log('wrote apstat-park/music/' + path);
  }
  for (const path of staleSongs().concat(staleFrozen())) {
    rmSync(resolve(RUNTIME, path));
    console.log('removed apstat-park/music/' + path + ' (no longer in the handoff)');
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
