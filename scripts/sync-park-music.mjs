// Copies the tracker handoff (handoff/audio/tracker/, Grok's editing home: demo.html + faithful.py)
// into the park's runtime tree, apstat-park/music/. The three classic scripts are wrapped as ES
// modules so the park imports them with its ?v=<APP_BUILD> query like every other park module;
// the song JSON files are copied byte for byte (their `mix` blocks are the teacher's approved
// settings). apstat-park/music-sync.test.mjs fails when the copies drift from the handoff.
//   node scripts/sync-park-music.mjs          # write
//   node scripts/sync-park-music.mjs --check  # exit 1 when anything differs
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const HANDOFF = resolve(root, 'handoff/audio/tracker');
export const RUNTIME = resolve(root, 'apstat-park/music');
export const SCRIPTS = ['tracker-engine.js', 'vibe.js', 'palette.js'];

export function wrapClassic(name, source) {
  return '// Generated by scripts/sync-park-music.mjs from handoff/audio/tracker/' + name + ' — edit the handoff, then re-run the sync.\n'
    + 'const module = { exports: {} };\n'
    + source.replace(/\r\n/g, '\n')
    + (source.endsWith('\n') ? '' : '\n')
    + 'export default module.exports;\n';
}

export function songFiles() {
  return readdirSync(resolve(HANDOFF, 'songs')).filter(f => f.endsWith('.json')).sort();
}

// [published path, expected contents] for everything the sync owns.
export function expected() {
  const out = [];
  for (const name of SCRIPTS) {
    out.push([name.replace(/\.js$/, '.mjs'), wrapClassic(name, readFileSync(resolve(HANDOFF, name), 'utf8'))]);
  }
  for (const file of songFiles()) out.push(['songs/' + file, readFileSync(resolve(HANDOFF, 'songs', file), 'utf8')]);
  return out;
}

export function drift() {
  const out = [];
  for (const [path, body] of expected()) {
    const target = resolve(RUNTIME, path);
    if (!existsSync(target) || readFileSync(target, 'utf8') !== body) out.push(path);
  }
  return out;
}

function main() {
  const check = process.argv.includes('--check');
  if (check) {
    const stale = drift();
    if (stale.length) { console.error('park music out of sync: ' + stale.join(', ')); process.exit(1); }
    console.log('park music in sync');
    return;
  }
  mkdirSync(resolve(RUNTIME, 'songs'), { recursive: true });
  for (const [path, body] of expected()) {
    writeFileSync(resolve(RUNTIME, path), body);
    console.log('wrote apstat-park/music/' + path);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
