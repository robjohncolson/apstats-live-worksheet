// Keep the synchronous browser fallback identical to the authoritative map.
import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../2026-crosswalk.json', import.meta.url);
const output = new URL('../js/ced2026-crosswalk.js', import.meta.url);
const { map } = JSON.parse(readFileSync(source, 'utf8'));
const text = '// Generated by scripts/build-ced2026-label-data.mjs. Do not edit by hand.\n'
  + 'window.CED2026_CROSSWALK = ' + JSON.stringify(map, null, 2) + ';\n';

if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== text) throw new Error('CED label fallback differs from 2026-crosswalk.json');
} else {
  writeFileSync(output, text);
}
