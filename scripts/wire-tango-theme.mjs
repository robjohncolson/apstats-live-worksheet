export function themeBlock() {
  return `<style id="${BLOCK_ID}">${THEME_CSS}</style>`;
}

const EXISTING_BLOCK_RE = new RegExp(`\\n?\\s*<style id="${BLOCK_ID}">[\\s\\S]*?</style>`, 'g');

export function wireHtml(html) {
  const stripped = html.replace(EXISTING_BLOCK_RE, '');
  const firstClose = stripped.indexOf('</style>');
  if (firstClose === -1) {
    return { html, changed: false, reason: 'no-style-block' };
  }
  const insertAt = firstClose + '</style>'.length;
  const next = `${stripped.slice(0, insertAt)}\n    ${themeBlock()}${stripped.slice(insertAt)}`;
  return { html: next, changed: next !== html, reason: next === html ? 'up-to-date' : 'wired' };
}

export function hasCurrentTheme(html) {
  return html.includes(themeBlock());
}

function main() {
  const apply = process.argv.includes('--apply');
  const filenames = fs.readdirSync(ROOT).filter((f) => WORKSHEET_RE.test(f)).sort();
  let changed = 0;
  for (const filename of filenames) {
    const full = path.join(ROOT, filename);
    const raw = fs.readFileSync(full, 'utf8');
    const result = wireHtml(raw);
    if (!result.changed) {
      continue;
    }
    changed += 1;
    console.log(`${apply ? 'wired' : 'would wire'} ${filename} (${result.reason})`);
    if (apply) {
      fs.writeFileSync(full, result.html);
    }
  }
  console.log(`${apply ? 'Applied' : 'Dry run'}: ${changed}/${filenames.length} worksheets ${apply ? 'updated' : 'need updating'}.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
