window.LESSON_CONTEXT_U5L3 = `
VIDEO 1 - Central Limit Theorem & Simulation:
- A sampling distribution of a statistic is the distribution of values for the statistic for all possible samples of the same size from a given population
- Example: sampling distribution of sample means for US teenager resting heart rates with n=28
- It's nearly impossible to get all possible samples, but we can SIMULATE a sampling distribution
- Rice University applet demonstrates with 10,000 random samples
- Key findings from simulation:
  * Normal population + small sample (n=2): sampling distribution is approximately normal
  * Normal population + larger sample (n=25): still normal, but with SMALLER standard deviation
  * Skewed population + small sample (n=2): sampling distribution is ALSO skewed (not normal)
  * Skewed population + larger sample (n=25): sampling distribution becomes approximately normal
  * Extreme U-shaped population + small sample (n=2): creates three clusters (not normal)
  * Extreme U-shaped population + larger sample (n=25): becomes approximately normal
- Central Limit Theorem: when sample size is sufficiently large, the sampling distribution of the mean will be approximately normally distributed, REGARDLESS of population shape

VIDEO 2 - Randomization Distributions:
- Melatonin experiment: 16 nursing mothers randomly assigned to Melatonin or Placebo
- Response variable: total hours newborn slept during the night
- Results: Melatonin mean = 11.07 hours, Placebo mean = 9.38 hours, difference = 1.69 hours
- Randomization distribution: collection of statistics generated by repeatedly REASSIGNING response values to treatment groups (with total disregard for where they came from)
- Process: Take all values, randomly assign 8 to Melatonin group, remaining 8 to Placebo group, calculate difference in means, repeat
- After 1000 trials, the distribution takes on a bell shape
- Only 12 out of 1000 simulations produced a difference >= 1.69 hours
- Probability = 0.012 (small probability = unlikely to happen by chance)
- Conclusion: It is unlikely the observed difference happened by chance alone; provides convincing evidence that melatonin increases newborn sleep
`;

