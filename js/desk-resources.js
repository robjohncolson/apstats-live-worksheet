// Shared save path for both worksheet and quiz Done. Called after the score
// has been validated (score === null for non-quiz artifacts).
// Applies optimistic UI mutation before the async write, then re-renders or
// rolls back depending on the result. perDay: blooket only (see _blooketCommit).
async function _studentMarkSave(btn, topicId, artifact, score, perDay, identity) {
    var directSave = !identity;
    identity = identity || _ftCaptureOwner();
    if (!_ftOwnerIsCurrent(identity)) {
        if (directSave && !(typeof _mayScore === 'function' && !_mayScore()) && typeof showDialog === 'function') {
            showDialog('⚠️', 'Your sign-in changed in another app. Sign in again on the Desk before saving your work.', 'OK');
        }
        return false;
    }
    // Optimistic mutation: go straight to "✓ Completed" — no interim state.
    // localStorage write (the source of truth per 540d168) happens inside
    // recordProgress FIRST, so this matches reality immediately.
    if (btn) {
        btn.disabled = true;
        btn.textContent = '✓ Completed';
        btn.style.opacity = '0.6';
    }
    var ok = await recordProgress(topicId, artifact, score);
    // The local write belongs to the captured owner. Even a resolved promise
    // yields: do not send its ledger row or repaint under a later sign-in.
    if (!_ftOwnerIsCurrent(identity)) return false;

    // Phase 4a+ compat: ALSO write the self-attest ledger row (_deskDoneRow) so the
    // teacher-dashboard's completion readouts AND the CROSS-DEVICE Done/grey-out
    // reflect Done clicks. Only once the local save succeeded.
    if (ok) _deskDoneRow(topicId, artifact, score, perDay);

    if (ok && _lastResourcePanel) {
        showResourcePanel(_lastResourcePanel.inf, _lastResourcePanel.dateStr);
        // Re-render the calendar so the sequential lesson gate updates —
        // completing a worksheet/blooket can unlock the next lesson live.
        if (typeof rCal === 'function') { try { rCal(); } catch (_) {} }
        // W4: refresh the Do Now grade pills now that work was marked Done.
        // typeof-guarded fire-and-forget, mirroring renderDoNow's call site.
        try {
            if (typeof renderDoNowGrades === 'function'
                && window.rosterClient && typeof window.rosterClient.token === 'function') {
                var _dnBase = window.ROSTER_SERVICE_URL;
                var _dnTok = window.rosterClient.token();
                if (_dnBase && _dnTok) {
                    renderDoNowGrades(_dnBase, _dnTok).catch(function () {});
                }
            }
        } catch (_) {}
        // Refresh the Do Now MESSAGE too (not just the pills) so it advances off
        // the just-completed lesson. rCal ran first, so _calNextUp is fresh and the
        // reconciliation in renderDoNow points at the new next-up. Fire-and-forget.
        // (Placed AFTER the W4 block so it doesn't shift that block out of the
        // grade-pipeline-w4 test's fixed-length _studentMarkSave slice.)
        try { if (typeof renderDoNow === 'function') renderDoNow(); } catch (_) {}
    } else if (btn) {
        btn.disabled = false;
        btn.innerHTML = '&#10003; Done';
    }
    return ok;
}

