// follow the login. WS-/CR- rows are grade-inert (they match no manifest blank or quiz); a BL-
// row's score is the lesson's flashcard Blooket score, and the server keeps each BL item's best.
// Callers: _studentMarkSave after a local save, and _blooketCommit for a finished run that is
// not a new best. Never from a read-only view: the teacher must not record for the student.
function _deskDoneRow(topicId, artifact, score, perDay) {
    if (typeof _viewAsContext === 'function' && _viewAsContext()) return;
    if (typeof window !== 'undefined' && window.__WS_READ_ONLY__) return;
    try {
        if (!window.gradebookClient || typeof window.gradebookClient.record !== 'function') return;
        // A pair cell "4.7+4.8" records under its first key: the lesson its deck was dealt for.
        topicId = String(topicId == null ? '' : topicId).split('+')[0];
        // Accept combined topics ("4.1-2") too — [\d-] not just \d — so each
        // combined lesson gets a UNIQUE DESK_DONE itemId. Otherwise um=null
        // and every combined Done collapses to "WS-U?-DESK_DONE", colliding
        // on the (student_id,source,item_id,attempt) upsert key so only the
        // last one survives — which broke the cross-device grey-out for
        // combined lessons (CALENDAR_SYNC_BUILD.md). Mirrors _stuTopicId.
        var um = /^(\d+)\.([\d-]+)$/.exec(topicId);
        var unit = um ? 'U' + um[1] : null;
        // Per-artifact prefix keeps the three DESK_DONE rows distinct on the
        // upsert key (a lesson can have worksheet + quiz + blooket all done).
        // Blooket uses BL-; its source stays 'worksheet' (NOT 'blooket'). The
        // server maps BL-→'blooket' for selfDoneArtifacts.
        var idPrefix = artifact === 'quiz' ? 'CR-' : artifact === 'blooket' ? 'BL-' : 'WS-';
        var source = artifact === 'quiz' ? 'curriculum_quiz' : 'worksheet';
        // A flashcard run dealt from a per-day slice records -DESK_DAY (scored per
        // topic in a per-day group); every other Done keeps -DESK_DONE (spec D3).
        var suffix = (artifact === 'blooket' && perDay) ? '-DESK_DAY' : '-DESK_DONE';
        var itemId = idPrefix + (unit || 'U?')
                   + (um ? '-L' + um[2] : '')
                   + suffix;
        var rec = window.gradebookClient.record({
            source: source, itemId: itemId, unit: unit, topic: topicId,
            response: { selfAttest: artifact }, score: score, attempt: 1
        });
        if (rec && typeof rec.catch === 'function') rec.catch(function () {});
    } catch (_) {}
}

async function studentMark(btn, topicId, artifact) {
    // Codex BLOCKER fold P2: view-as is read-only -- the teacher must never
    // mark progress on the student's behalf. typeof-guarded so existing
    // vm-based studentMark tests don't need to inject the helper.
    if (typeof _viewAsContext === 'function' && _viewAsContext()) {
      if (typeof _showViewAsToast === 'function') {
        _showViewAsToast('Read-only view: cannot mark progress for this student.');
      }
      return;
    }
    if (!getStudentEmail()) { showDialog('\u{1F464}','Please sign in first (Student menu).','OK'); return; }
    // 2026-05-20 v2: Blooket Done now opens a flashcard quiz sourced from
    // the same Blooket CSV. Student must pass ≥80% on a single pass before
    // Done is recorded. This is the actual chain-of-custody check — naked
    // self-attest (and even self-reported scores) couldn't verify anything;
    // we control the flashcard flow end-to-end, so we know they at least
    // engaged with the material.
    if (artifact === 'blooket') {
        openBlooketFlashcards(btn, topicId);
        return;
    }
    if (artifact === 'quiz') {
        // The quiz score is recorded automatically from the curriculum_render
        // quiz (no self-report). _doneBtn only enables this button once the
        // recorded performance clears the gate (answered >=40% AND scored
        // >=40%), so a click just records the Done mark — carrying the recorded
        // score % for the teacher's legacy student_progress view.
        var perf = (typeof _quizPerfFor === 'function') ? _quizPerfFor(topicId) : null;
        await _studentMarkSave(btn, topicId, artifact, perf ? perf.scorePct : null);
        return;
    }
    // Non-quiz path (worksheet, video): proceed directly. Blooket is
    // intercepted earlier and routed through openBlooketFlashcards.
    await _studentMarkSave(btn, topicId, artifact, null);
}
