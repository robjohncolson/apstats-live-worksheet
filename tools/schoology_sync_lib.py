# The CED-2026 title switch (CED2026_SINGLE_SOURCE_SPEC.md section 3). False = the
# OLD titles ("3.1 Blooket"); True = the CED titles ("1.10 Day 1 Blooket"). Flip it
# ONLY after tools/schoology_rename_columns.py --apply has renamed the live columns:
