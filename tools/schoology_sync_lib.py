SYNC_CONFIG_PATH = os.path.join(_TOOLS_DIR, "schoology_sync_config.json")
# Generated by scripts/build-ced-column-titles.mjs from the shared crosswalk.
CED_TITLES_PATH = os.path.join(_REPO_ROOT, "data", "ced-column-titles.json")

# The one-time rename's manifest (written ONLY by tools/schoology_rename_columns.py):
#   { "<section>": { "status": "not-started" | "in-progress" | "done",
#                    "renamed":  { "<column_key>": {oldTitle, newTitle, nid, at} },
#                    "inFlight": {key, nid, oldTitle, newTitle} | null,
#                    "startedAt": iso, "finishedAt": iso } }
# Title presence is NOT identity during the migration (old 6.1-2 becomes "3.3 Follow-Along",
# which is also old 3.3's OLD title), so migration state lives here, not in the gradebook.
RENAME_STATE_PATH = os.path.join(_TOOLS_DIR, ".schoology-rename-state.json")
# PeriodY is the summer mock alias of Period B's course: it shares Period B's manifest.
RENAME_STATE_SECTION = {"PeriodY": "PeriodB"}
RENAME_STATUSES = ("not-started", "in-progress", "done")

_ced_columns_cache = None


def _env_path(env_name: str, default: str) -> str:
    """Tests point these at a temp dir (tests/conftest.py) so machine state never leaks in."""
    return os.environ.get(env_name) or default


def rename_state_path(path: str | None = None) -> str:
    return path or _env_path("SCHOOLOGY_RENAME_STATE", RENAME_STATE_PATH)


def load_rename_state(path: str | None = None) -> dict:
    """The rename manifest ({} when the rename never started)."""
    path = rename_state_path(path)
    if not os.path.exists(path):
        return {}
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def save_rename_state(state: dict, path: str | None = None) -> None:
    """Atomic write: a crash mid-save never leaves a half-written manifest."""
    path = rename_state_path(path)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        json.dump(state, f, indent=2, sort_keys=True)
        f.write("\n")
    os.replace(tmp, path)


def rename_state_section(section: str) -> str:
    return RENAME_STATE_SECTION.get(section, section)


def rename_status(state: dict, section: str) -> str:
    entry = state.get(rename_state_section(section)) or {}
    status = entry.get("status") or "not-started"
    if status not in RENAME_STATUSES:
        raise ValueError(f"Unknown rename status {status!r} for {section} in the rename manifest")
    return status

KIND_TO_CATEGORY = {
    'lesson': 'Lesson',
    'quiz': 'Quizzes',
    'poster': 'Posters',
    'blooket': 'Blooket',
    'progress_check': 'Progress Check',
}


def classify_lesson_key(lesson_key: str) -> str:
    """Return one of 'lesson','quiz','poster','blooket','progress_check'.

    Rules are checked in this order (case-insensitive):
      1. Contains 'PC' or 'progress'               -> 'progress_check'
      2. Contains 'QUIZ'                            -> 'quiz'
      3. Contains 'POSTER'                          -> 'poster'
      4. Contains 'BLOOKET'                         -> 'blooket'
      5. Looks like a topic number (e.g. "1.1",
         "U4.1-2", "4.1")                          -> 'lesson'
      6. Anything else                              -> 'lesson'  (safe default)
    """
    if not lesson_key:
        return 'lesson'

    upper = lesson_key.upper()

    if 'PC' in upper or 'PROGRESS' in upper:
        return 'progress_check'

    if 'QUIZ' in upper:
        return 'quiz'

    if 'POSTER' in upper:
        return 'poster'

    if 'BLOOKET' in upper:
        return 'blooket'

    # Topic pattern: optional "U" prefix, then digit(s).digit(s) with optional range suffix.
    # Examples: "1.1", "U4.1-2", "4.1", "U1.10"
    if re.search(r'^U?\d+\.\d+', upper):
        return 'lesson'

    return 'lesson'


