def schoology_titles_ced(config_path: str | None = None) -> bool:
    """The SCHOOLOGY_TITLES_CED switch from tools/schoology_sync_config.json.

    A missing file or key means False (the old titles). Anything but a real JSON
    true is False, so a typo can never flip the sync to titles that do not exist.
    """
    path = config_path or _env_path("SCHOOLOGY_SYNC_CONFIG", SYNC_CONFIG_PATH)
    if not os.path.exists(path):
        return False
    with open(path, "r", encoding="utf-8") as f:
        config = json.load(f)
    return config.get("schoology_titles_ced") is True


def load_ced_columns(path: str | None = None) -> dict:
    """{column_key: entry} from data/ced-column-titles.json (loaded once per process)."""
    global _ced_columns_cache
    if path is not None:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)["columns"]
    if _ced_columns_cache is None:
        with open(CED_TITLES_PATH, "r", encoding="utf-8") as f:
            _ced_columns_cache = json.load(f)["columns"]
    return _ced_columns_cache


def ced_column_title(column_key: str) -> str:
    """The CED-2026 Schoology title for a sync column key ('BL:3.1' -> '1.10 Day 1 Blooket').

    A key missing from the fixture RAISES: the sync must never invent a title,
    because a title Schoology does not have means a brand-new duplicate column.
    """
    entry = load_ced_columns().get(column_key)
    if entry is None:
        raise KeyError(
            f"No CED title for column {column_key!r} in data/ced-column-titles.json -- "
            "re-run node scripts/build-ced-column-titles.mjs"
        )
    return entry["ced"]


def lesson_label_for_comment(lesson_key: str, ced: bool | None = None) -> str:
    """The lesson name a grade-cell comment may print ('3.2' -> '1.10 Day 2' once the
    Schoology titles are CED; the old key while they are not).

    Derived from the CED title of the lesson's Follow-Along column (the kind suffix
    stripped), so a comment and the column it sits in always agree. Falls back to
    the old key when the lesson has no CED column (never raises: a comment is not a
    column title, a stale label is better than no comment).
    """
    if ced is None:
        ced = schoology_titles_ced()
    label = str(lesson_key)
    if not ced:
        return label
    entry = load_ced_columns().get(f"FA:{label}")
    if entry is None:
        return label
    return re.sub(r"\s+Follow-Along$", "", entry["ced"])


def column_key_for(kind: str, lesson_key: str) -> str:
    """The sync column key for (kind, key): ('blooket','3.1') -> 'BL:3.1'.

    Keys that already carry a prefix ('FA:3.6-7', 'PC:U1') pass through.
    """
    if ":" in str(lesson_key):
        return str(lesson_key)
    if kind == 'progress_check':
        return f"PC:U{_parse_unit_from_key(lesson_key)}"
    if kind == 'poster':
        return f"POSTER:U{_parse_unit_from_key(lesson_key)}"
    prefix = {'lesson': 'FA', 'quiz': 'QUIZ', 'blooket': 'BL'}.get(kind)
    if prefix is None:
        raise KeyError(f"No CED column kind for {kind!r}")
    return f"{prefix}:{re.sub(r'^[Uu]', '', str(lesson_key))}"


def assignment_title(kind: str, lesson_key: str, topic_name: str | None = None,
                     ced: bool | None = None) -> str:
    """Build a human-readable Schoology assignment title.

    ced=None reads SCHOOLOGY_TITLES_CED from tools/schoology_sync_config.json.
    ced=False: the legacy titles, byte-for-byte as before.
    ced=True:  the CED-2026 title from data/ced-column-titles.json (missing key raises).
    """
    if ced is None:
        ced = schoology_titles_ced()
    if ced:
        return ced_column_title(column_key_for(kind, lesson_key))

    if kind == 'lesson':
        unit, topic_range = _parse_topic_numbers(lesson_key)
        if topic_range:
            topic_label = f'{unit}.{topic_range}'
        else:
            topic_label = lesson_key

        if topic_name:
            return f'Topic {topic_label}: {topic_name}'
        return f'Topic {topic_label}'

    if kind == 'progress_check':
        unit = _parse_unit_from_key(lesson_key)
        return f'Unit {unit} Progress Check'

    if kind == 'quiz':
        if topic_name:
            return f'Quiz: {topic_name}'
        return f'Quiz {lesson_key}'

    if kind == 'poster':
        unit = _parse_unit_from_key(lesson_key)
        return f'Unit {unit} Poster'

    if kind == 'blooket':
        return f'Blooket {lesson_key}'

    # Unknown kind -- fall back gracefully
    return lesson_key


def assignment_points(kind: str | None = None) -> int:
    """All assignment types are worth 100 points."""
    return 100


def marking_period_for_date(date_iso: str, mp_ranges: dict) -> str | None:
    """Return the grading_period_id that contains date_iso (inclusive), or None.

    mp_ranges format::
        { grading_period_id: {'start': 'YYYY-MM-DD', 'end': 'YYYY-MM-DD'} }

    ISO date strings compare correctly as plain strings (lexicographic == chronological).
    A None or empty date_iso returns None.
    """
    if not date_iso:
        return None

    for period_id, bounds in mp_ranges.items():
        start = bounds.get('start', '')
        end = bounds.get('end', '')
        if start and end and start <= date_iso <= end:
            return period_id

    return None


def should_push(target_value, last_synced_value, tol: float = 1e-9) -> bool:
    """Decide whether a grade needs to be pushed to Schoology.

    Rules:
      - target_value is None  -> False  (nothing to push)
      - last_synced_value is None and target is not None -> True (first push)
      - Both numeric: True iff abs difference > tol
      - Non-numeric fallback: compare as strings
    """
    if target_value is None:
        return False

    if last_synced_value is None:
        return True

    try:
        return abs(float(target_value) - float(last_synced_value)) > tol
    except (TypeError, ValueError):
        return str(target_value) != str(last_synced_value)


def plan_assignment_work(scope_keys: list, existing: dict) -> dict:
    """Split scope_keys into assignments that need creating vs. those that can be reused.

    existing format::
        { lesson_key: {'schoology_assignment_id': id_or_None} }

    Returns::
        {'create': [...], 'reuse': [...]}

    Order follows scope_keys; duplicates are removed (first occurrence wins).
    """
    seen = set()
    create = []
    reuse = []

    for key in scope_keys:
        if key in seen:
            continue
        seen.add(key)

        row = existing.get(key)
        if row is None:
            create.append(key)
        else:
            sid = row.get('schoology_assignment_id')
            if sid is None:
                create.append(key)
            else:
                reuse.append(key)

    return {'create': create, 'reuse': reuse}


def compute_sync_actions(targets: dict, last_synced: dict) -> dict:
    """Determine which grade entries need pushing vs. skipping.

    targets / last_synced are keyed by any hashable id
    (e.g. a (student_id, lesson_key) tuple or a plain string).

    Returns::
        {
          'push': [keys where should_push is True],
          'skip': [keys where target is not None but should_push is False],
        }

    Keys whose target is None are omitted entirely.
    Iteration order follows targets.
    """
    push = []
    skip = []

    for key, target_value in targets.items():
        if target_value is None:
            continue

        last_value = last_synced.get(key)
        if should_push(target_value, last_value):
            push.append(key)
        else:
            skip.append(key)

    return {'push': push, 'skip': skip}
